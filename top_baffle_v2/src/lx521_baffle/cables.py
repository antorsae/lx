def _lm_tube_sections(um_handoff_key: str = "proud",
                      spacing_mm: float = 2.0):
    """Centerline sections and smooth D8.2->D9 terminal flare radii."""
    plan = _lm_plan_spline(um_handoff_key=um_handoff_key)
    count = max(12, int(math.ceil(plan.length / spacing_mm)))
    points = [tuple(plan @ (index / count)) for index in range(count + 1)]
    distances = [0.0]
    for first, second in zip(points[:-1], points[1:]):
        distances.append(distances[-1] + math.dist(first, second))
    flare_start = max(0.0, distances[-1] - LM_EXIT_FLARE_LENGTH_MM)
    base_radius = CABLE_D["lm"] / 2.0
    exit_radius = LM_EXIT_D_MM / 2.0
    radii = []
    for distance in distances:
        u = min(1.0, max(
            0.0,
            (distance - flare_start)
            / max(LM_EXIT_FLARE_LENGTH_MM, 1.0e-12),
        ))
        smooth = u * u * (3.0 - 2.0 * u)
        radii.append(base_radius + (exit_radius - base_radius) * smooth)
    handoff = lm_handoff_points(
        n=32, um_handoff_key=um_handoff_key)
    points.extend(handoff[1:])
    radii.extend([exit_radius] * (len(handoff) - 1))
    return points, radii


