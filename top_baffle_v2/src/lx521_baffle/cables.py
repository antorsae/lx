def _ts_captive_nudge_mm(y: float) -> float:
    """Positive-X stock/slim TS detour preserving the full D6 lumen.

    The left TS lane lies at negative X, so positive X is toward the baffle
    centreline and away from the lower-left captive land.  The short plateau
    brackets the released magnet station; both ramps have zero end slope.
    """
    if y <= TS_CAPTIVE_NUDGE_KNOTS[0][0]:
        return 0.0
    if y >= TS_CAPTIVE_NUDGE_KNOTS[-1][0]:
        return 0.0
    for (y0, x0), (y1, x1) in zip(
            TS_CAPTIVE_NUDGE_KNOTS,
            TS_CAPTIVE_NUDGE_KNOTS[1:]):
        if y <= y1:
            weight = _smoothstep01((y - y0) / (y1 - y0))
            return x0 + weight * (x1 - x0)
    raise AssertionError("unreachable V1 TS nudge interval")


def _ts_route(ts_route_key: str = TS_ROUTE_STANDARD):
    """The shared tweeter duct: left tangent+arc r=116.5 (outside the
    W22 pilot ring AND the U22 recess rim, surface-to-rim 2.9), the
    left vase flank lane, crest transition (bowed 1 mm outboard of
    the deepened 148-deg MU10 pilot), notch-corridor dive, single
    scallop pierce at (-3.3, ~430). Section per ts_section(): O6.0
    z=11.5 outside the vase, W6.6 x H4.4 oval at zc=10.45 under the
    MU10 flange seat."""
    # straight run to the arc tangent point: keep the knots SPARSE --
    # long runs of collinear spline knots degenerate OCC's pipe frame
    line = [(-16.8, 58.8), (-48.9, 88.0)]
    route = (
        line
        + _arc(116.5, [-133.99, -142, -152, -162, -172, -182, -192,
                       -202, -212])
        # The original interpolating spline bowed 0.085 mm through the
        # V1L/B2 lower-left outline between the final arc knots and the
        # waist controls.  These seven points are weighted along the
        # exact inward wall normal; they retain the established route
        # everywhere else while restoring 1.769 mm of normal wall.
        + [(-86.390863, 278.580334),
           (-71.260789, 291.898299),
           (-53.534004, 301.629510),
           (-45.665208, 305.405283),
           (-37.997095, 309.848260),
           (-34.082604, 313.202641),
           (-33.214491, 317.145618),
           (-33.3, 320.5), (-34.1, 324.0),
           (-35.3, 327.5), (-36.6, 330.8)]
        + [(-(_wall_x(y) - LANE_OFFSET), y)
           for y in (338, 346, 354, 362, 370, 378, 384)]
        + [(-53.3, 386.5), (-52.2, 389.5), (-50.2, 392.0),
           (-47.6, 393.3), (-45.0, 394.5), (-42.7, 395.7), (-40.7, 397.0)]
        + [(-38.0, 399.0), (-31.0, 402.0), (-25.6, 404.8), (-20.3, 407.5),
           (-15.5, 410.0), (-10.4, 412.8), (-5.5, 417.5), (-4.3, 420.5),
           (-3.5, 424.0), (-3.3, 427.0), (-3.3, 430.0), (-3.4, 433.0)]
    )
    if ts_route_key == TS_ROUTE_STANDARD:
        return route
    if ts_route_key == TS_ROUTE_CAPTIVE:
        return [
            (x + _ts_captive_nudge_mm(y), y)
            for x, y in route
        ]
    raise ValueError(
        f"unknown TS route key {ts_route_key!r}; choose "
        f"{TS_ROUTE_STANDARD!r} or {TS_ROUTE_CAPTIVE!r}")


