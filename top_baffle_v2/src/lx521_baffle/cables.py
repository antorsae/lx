"""Cable routing profiles for the proud family and skeletal Obi-Wan.

``LX_ROUTING_PROFILE=proud`` (R6P, the default) is the subtractive
route used by B2 and V1 and, with a keyed terminal handoff, V1L.  Its
standard UM main follows the proven outer
U22 arc, returns through the broad lower neck, and then turns through a
true R14 three-dimensional elbow to the rear outlet at (33.45, 301.49).
The old planar-main/vertical-cylinder 90 degree collision is gone: the
complete handoff is one continuous sweep.  The route is D8.2 end to end,
raising nominal radial slack around the estimated D7 cable from 0.4 to
0.6 mm.  The outlet bearing is 297.4 degrees from the MU center: still
between the lower screws, but laterally clear of the conservative 283
degree Faston pull envelope and its rear cable continuation.

V1L keeps the same upstream R6P route but refits its terminal plan span
into a second G1 R14 handoff.  The center of that bore at V1L's physical
rear plane z=6.8 is exactly 60.0 mm from the MU center on the 283-degree
terminal axis.  This exception is selected explicitly by the V1L split
builder; every other proud-family builder retains the standard outlet.

``LX_ROUTING_PROFILE=obiwan`` (R6F) selects the isolated two-carrier
platform. The LM lead uses the same R14 rear-face handoff contract as the
proud family, with a D9 terminal flare followed by a tangent free external
span. The UM
passage is printed only in LM; the shared-tweeter passage is printed only in
LM/UM. Those printed-owner spans are generated by
``top_baffle_nd25fw4_obiwan_route`` with continuous 0.8 mm minimum skins and
smooth, fully covered local Z bumps around crossed insert envelopes. UM then
floats behind its carrier and T floats behind the tweeter crescent. There is
no detachable external raceway or printed Obi-Wan grommet.

Within R6P, the LM and tweeter routes retain their established mouth datums.
The former LM planar-main/vertical-bore collision is replaced by a continuous
R14 handoff whose centerline reaches that exact rear-face datum.  The terminal
10 mm flares from D8.2 to D9 so the estimated D7.8 lead retains useful fishing
clearance through the bend.  The proud and Obi-Wan physical centerlines,
including their intentional free spans, are checked by ``test_clearances.py``
and ``test_obiwan_r6f.py`` using full-centerline curvature rather than
horizontal gaps.
"""

