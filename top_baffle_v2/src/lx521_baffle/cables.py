def lm_exit_handoff_spec(
        planar_z_mm: float,
        rear_face_z_mm: float,
        rear_end_z_mm: float = LM_DUCT_OUT_REAR_Z_MM,
        radius_mm: float = LM_EXIT_BEND_R_MM,
        plan_bearing_deg: float = 90.0,
        face_xy_mm=None) -> dict:
    """Return the exact gradual LM rear-face handoff geometry.

    The bend begins horizontal along ``plan_bearing_deg``, follows a circular
    radius in the plane spanned by that plan tangent and -Z, reaches the
    selected mouth center on the actual rear face, then continues outside the
    print along that exact tangent.  ``face_xy_mm`` defaults to the common
    Stock/Slim/floor outlet datum; a family-specific caller may provide an
    explicitly qualified alternative without changing that shared datum.
    """
    planar_z_mm = float(planar_z_mm)
    rear_face_z_mm = float(rear_face_z_mm)
    rear_end_z_mm = float(rear_end_z_mm)
    radius_mm = float(radius_mm)
    plan_bearing_deg = float(plan_bearing_deg)
    if face_xy_mm is None:
        face_xy_mm = (LM_DUCT_OUT_X_MM, LM_DUCT_OUT_Y_MM)
    if len(face_xy_mm) != 2:
        raise ValueError("LM rear-face mouth needs one XY pair")
    face_xy_mm = tuple(map(float, face_xy_mm))
    drop = planar_z_mm - rear_face_z_mm
    if not 0.0 < drop < radius_mm:
        raise ValueError(
            "LM rear face must lie within one gradual bend radius: "
            f"drop={drop:.6f}, radius={radius_mm:.6f}")
    if rear_end_z_mm >= rear_face_z_mm:
        raise ValueError("LM external endpoint must lie behind the rear face")

    cos_phi = 1.0 - drop / radius_mm
    phi = math.acos(cos_phi)
    sin_phi = math.sin(phi)
    plan_angle = math.radians(plan_bearing_deg)
    plan_tangent = (
        math.cos(plan_angle), math.sin(plan_angle), 0.0)
    face = (
        face_xy_mm[0],
        face_xy_mm[1],
        rear_face_z_mm,
    )
    start = (
        face[0] - radius_mm * sin_phi * plan_tangent[0],
        face[1] - radius_mm * sin_phi * plan_tangent[1],
        planar_z_mm,
    )
    face_tangent = (
        cos_phi * plan_tangent[0],
        cos_phi * plan_tangent[1],
        -sin_phi,
    )
    external_length = (rear_face_z_mm - rear_end_z_mm) / sin_phi
    rear_end = tuple(
        face[index] + external_length * face_tangent[index]
        for index in range(3))
    half_phi = phi / 2.0
    arc_mid = (
        start[0] + radius_mm * math.sin(half_phi) * plan_tangent[0],
        start[1] + radius_mm * math.sin(half_phi) * plan_tangent[1],
        planar_z_mm - radius_mm * (1.0 - math.cos(half_phi)),
    )
    return {
        "radius_mm": radius_mm,
        "diameter_mm": LM_EXIT_D_MM,
        "planar_z_mm": planar_z_mm,
        "rear_face_z_mm": rear_face_z_mm,
        "rear_end_z_mm": rear_end_z_mm,
        "face_angle_rad": phi,
        "face_angle_deg_from_plan": math.degrees(phi),
        "face_angle_deg_from_rear_normal": 90.0 - math.degrees(phi),
        "plan_bearing_deg": plan_bearing_deg,
        "plan_tangent": plan_tangent,
        "start": start,
        "arc_mid": arc_mid,
        "face": face,
        "face_tangent": face_tangent,
        "rear_end": rear_end,
        "external_length_to_rear_end_mm": external_length,
    }


def lm_exit_handoff_points(
        planar_z_mm: float,
        rear_face_z_mm: float,
        n: int = 48,
        rear_end_z_mm: float = LM_DUCT_OUT_REAR_Z_MM,
        radius_mm: float = LM_EXIT_BEND_R_MM,
        plan_bearing_deg: float = 90.0,
        face_xy_mm=None):
    """Sample the analytic R14 arc plus its tangent external continuation."""
    if n < 2:
        raise ValueError("LM handoff needs at least two arc intervals")
    spec = lm_exit_handoff_spec(
        planar_z_mm, rear_face_z_mm, rear_end_z_mm, radius_mm,
        plan_bearing_deg, face_xy_mm=face_xy_mm)
    sx, sy, sz = spec["start"]
    tx, ty, _tz = spec["plan_tangent"]
    phi_face = spec["face_angle_rad"]
    out = []
    for index in range(n + 1):
        phi = phi_face * index / n
        out.append((
            sx + radius_mm * math.sin(phi) * tx,
            sy + radius_mm * math.sin(phi) * ty,
            sz - radius_mm * (1.0 - math.cos(phi)),
        ))
    arc_step_mm = radius_mm * phi_face / n
    lead_count = max(
        1,
        int(math.ceil(
            spec["external_length_to_rear_end_mm"]
            / max(arc_step_mm, 1.0e-12))),
    )
    face = spec["face"]
    rear_end = spec["rear_end"]
    for index in range(1, lead_count + 1):
        u = index / lead_count
        out.append(tuple(
            face[axis] + u * (rear_end[axis] - face[axis])
            for axis in range(3)))
    return out


