def _rear_plane_crossing_xy(start, end):
    """XY where one oblique stock/slim entry crosses the z=0 datum."""
    fraction = -start[2] / (end[2] - start[2])
    return (
        start[0] + fraction * (end[0] - start[0]),
        start[1] + fraction * (end[1] - start[1]),
    )


